void SelectMusicTrackAfterTransition(GBState *gb) {
    if (!gb) return;

    /* If the game requested the music track to continue after the transition, return immediately */
    if (gb_read_hram(gb, hContinueMusicAfterWarp) != 0) {
        gb_write_hram(gb, hContinueMusicAfterWarp, 0);
        return;
    }

    uint8_t d = MUSIC_OVERWORLD_SWORDLESS;

    /* If wSwordLevel == 0 (Link doesn't have sword yet), use adventure start music */
    if (gb_read(gb, wSwordLevel) == 0) {
        gb_write(gb, wBossDefeated, 0);
    } else {
        uint8_t map_room = gb_read_hram(gb, hMapRoom);
        d = OverworldMusicTracks[map_room];

        /* Clear hNextMusicTrackToFadeInto */
        gb_write_hram(gb, hNextMusicTrackToFadeInto, 0);

        /* If wIsIndoor == 0, skip further code and load the soundtrack */
        if (gb_read(gb, wIsIndoor) == 0) {
            gb_write(gb, wBossDefeated, 0);
        } else {
            /* If a boss was just defeated, load specific music */
            if (gb_read(gb, wBossDefeated) != 0) {
                d = MUSIC_AFTER_BOSS;
            } else {
                uint8_t map_id = gb_read_hram(gb, hMapId);
                uint8_t a = map_id;

                if (map_id == MAP_COLOR_DUNGEON) {
                    a = 0x09;
                } else if (map_id == MAP_HOUSE) {
                    if (gb_read_hram(gb, hMapRoom) == ROOM_INDOOR_B_CAMERA_SHOP) {
                        a = 0x0F;
                    }
                }

                d = HouseMusicTracks[a];

                /* If hIsSideScrolling != 0 and a < $0A, force soundtrack to 2D underground */
                if (gb_read_hram(gb, hIsSideScrolling) != 0 && a < 0x0A) {
                    d = MUSIC_2D_UNDERGROUND;
                }
            }
        }
    }

    /* Set overworld soundtrack */
    uint8_t track = d;
    gb_write_hram(gb, hDefaultMusicTrack, track);
    SetWorldMusicTrack(gb, track);

    /* If soundtrack id <= $24 and MusicOverridesPowerUpTrack[soundtrack_id] == 1,
     * the map-defined music has precedence over power-up music */
    if (track <= 0x24) {
        if (MusicOverridesPowerUpTrack[track] != 0) {
            return;
        }
    }

    /* If Link currently has no power-up, return */
    if (gb_read(gb, wActivePowerUp) == 0) {
        return;
    }

    /* Replace current music by power-up music */
    gb_write(gb, wMusicTrackToPlay, MUSIC_ACTIVE_POWER_UP);
    gb_write_hram(gb, hDefaultMusicTrackAlt, MUSIC_ACTIVE_POWER_UP);
    gb_write_hram(gb, hNextDefaultMusicTrack, MUSIC_ACTIVE_POWER_UP);
    gb_write(gb, wC1CF, 0);
}
